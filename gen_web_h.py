"""Pack a self-contained UTF-8 phone webapp into an ESP32 PROGMEM header.

Usage: python gen_web_h.py [--source web/player.html] [--output web_player.h]
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parent


def render(html: str) -> str:
    delimiter = "VFPWEB"
    if f"){delimiter}\"" in html:
        raise ValueError("HTML contains the C++ raw-string terminator")
    if "<script>" not in html or "<style>" not in html:
        raise ValueError("Expected one self-contained HTML app")
    return (
        "#pragma once\n#include <pgmspace.h>\n"
        "// Generated by gen_web_h.py from web/player.html.\n"
        f"static const char WEB_PLAYER_HTML[] PROGMEM = R\"{delimiter}({html}){delimiter}\";\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "web" / "player.html")
    parser.add_argument("--output", type=Path, default=ROOT / "web_player.h")
    args = parser.parse_args()
    html = args.source.read_text(encoding="utf-8-sig")
    args.output.write_text(render(html), encoding="utf-8", newline="\n")
    print(f"Packed {len(html.encode('utf-8'))} HTML bytes into {args.output}")


if __name__ == "__main__":
    main()
